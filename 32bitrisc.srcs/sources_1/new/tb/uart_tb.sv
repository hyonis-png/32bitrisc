module uart_tb;

    //---------------------------------------------------------
    // Testbench Signals
    //---------------------------------------------------------
    logic clk;
    logic rst;

    logic start;

    logic [7:0] tx_data;
    logic [7:0] rx_data;

    logic serial_wire;

    logic tx_busy;
    logic valid;

    //---------------------------------------------------------
    // UART Transmitter
    //---------------------------------------------------------
    uart_tx tx_dut (

        .clk(clk),
        .rst(rst),

        .start(start),
        .data(tx_data),

        .tx(serial_wire),
        .busy(tx_busy)

    );

    //---------------------------------------------------------
    // UART Receiver
    //---------------------------------------------------------
    uart_rx rx_dut (

        .clk(clk),
        .rst(rst),

        .rx(serial_wire),

        .data(rx_data),
        .valid(valid)

    );

    //---------------------------------------------------------
    // 100 MHz Clock
    //---------------------------------------------------------
    always #5 clk = ~clk;

    //---------------------------------------------------------
    // Test Sequence
    //---------------------------------------------------------
    initial begin

        //-----------------------------------------------------
        // Initialize
        //-----------------------------------------------------
        clk      = 0;
        rst      = 1;

        start    = 0;

        tx_data  = 8'h00;

        //-----------------------------------------------------
        // Apply Reset
        //-----------------------------------------------------
        #20;

        rst = 0;

        #20;

        //-----------------------------------------------------
        // Transmit ASCII 'A'
        //-----------------------------------------------------
        tx_data = 8'h41;

        start = 1;

        #10;

        start = 0;

        //-----------------------------------------------------
        // Wait for receiver
        //-----------------------------------------------------
        wait(valid);

        //-----------------------------------------------------
        // Check Result
        //-----------------------------------------------------
        if(rx_data == 8'h41)
            $display("PASS! Received %h", rx_data);
        else
            $display("FAIL! Received %h", rx_data);

        #100;

        $finish;

    end

endmodule